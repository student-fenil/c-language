#include <stdio.h>

int main()
{
    int a = 99;
    float b = 30.9;
    char c = 'z';

    printf(" \n The value of a is : %d", a);
    printf(" \n The value of b is : %.1f", b);
    printf(" \n The value of c is : %c", c);

    return 0;
}



/*output
 The value of a is : 99 
 The value of b is : 30.9 
 The value of c is : z
*/